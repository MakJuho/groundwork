-- 회원
CREATE TABLE TB_MBR (
    MBR_ID          VARCHAR2(20)  NOT NULL,
    MBR_NM          VARCHAR2(50)  NOT NULL,
    HP_NO           VARCHAR2(13)  NOT NULL,
    EMAIL           VARCHAR2(100),
    BIRTH_YMD       CHAR(8),
    GRADE_CD        VARCHAR2(10)  DEFAULT 'GEN' NOT NULL,
    MBR_STAT        CHAR(1)       DEFAULT 'A' NOT NULL,
    SMS_RCV_YN      CHAR(1)       DEFAULT 'N' NOT NULL,
    EMAIL_RCV_YN    CHAR(1)       DEFAULT 'N' NOT NULL,
    JOIN_DT         DATE          DEFAULT SYSDATE NOT NULL,
    LAST_LOGIN_DT   DATE,
    DRMNT_DT        DATE,
    WTHDR_DT        DATE,
    GRADE_CHG_DT    DATE,
    RMK             VARCHAR2(500),
    REG_ID          VARCHAR2(20),
    UPD_ID          VARCHAR2(20),
    UPD_DT          DATE,
    CONSTRAINT PK_TB_MBR PRIMARY KEY (MBR_ID)
);

CREATE INDEX IX_TB_MBR_01 ON TB_MBR (HP_NO);
CREATE INDEX IX_TB_MBR_02 ON TB_MBR (MBR_STAT, LAST_LOGIN_DT);

-- 회원 등급 변경 이력 (배치 산정 + 관리자 수동 변경)
CREATE TABLE TB_MBR_GRADE_HIST (
    MBR_ID          VARCHAR2(20)  NOT NULL,
    HIST_SEQ        NUMBER(6)     NOT NULL,
    BF_GRADE_CD     VARCHAR2(10),
    AF_GRADE_CD     VARCHAR2(10)  NOT NULL,
    CHG_TYPE        CHAR(1)       DEFAULT 'M' NOT NULL,   -- B 배치, M 수동
    CNFM_AMT_6M     NUMBER(15),
    CHG_RSN         VARCHAR2(300),
    CHG_DT          DATE          DEFAULT SYSDATE NOT NULL,
    CHG_ID          VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_TB_MBR_GRADE_HIST PRIMARY KEY (MBR_ID, HIST_SEQ),
    CONSTRAINT FK_TB_MBR_GRADE_HIST FOREIGN KEY (MBR_ID) REFERENCES TB_MBR (MBR_ID)
);
