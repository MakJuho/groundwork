-- 배송
CREATE TABLE TB_DLV (
    DLV_NO        VARCHAR2(20)  NOT NULL,
    ORD_NO        VARCHAR2(20)  NOT NULL,
    CARRIER_CD    VARCHAR2(10),
    INVC_NO       VARCHAR2(20),
    DLV_STAT      CHAR(1)       DEFAULT 'R' NOT NULL,
    DLV_FEE       NUMBER(10)    DEFAULT 0 NOT NULL,
    ADD_FEE       NUMBER(10)    DEFAULT 0 NOT NULL,
    ISLAND_YN     CHAR(1)       DEFAULT 'N' NOT NULL,
    ISLAND_TYPE   VARCHAR2(10),
    RCV_ZIP       VARCHAR2(5),
    SHIP_DT       DATE,
    SHIP_ID       VARCHAR2(20),
    DLV_CMPL_DT   DATE,
    CMPL_ID       VARCHAR2(20),
    LAST_TRACE_DT DATE,
    REG_DT        DATE          DEFAULT SYSDATE NOT NULL,
    REG_ID        VARCHAR2(20),
    UPD_DT        DATE,
    UPD_ID        VARCHAR2(20),
    CONSTRAINT PK_TB_DLV PRIMARY KEY (DLV_NO)
);

CREATE UNIQUE INDEX UX_TB_DLV_01 ON TB_DLV (ORD_NO);
CREATE INDEX IX_TB_DLV_02 ON TB_DLV (DLV_STAT, SHIP_DT);
CREATE INDEX IX_TB_DLV_03 ON TB_DLV (CARRIER_CD, INVC_NO);

COMMENT ON TABLE  TB_DLV             IS '배송';
COMMENT ON COLUMN TB_DLV.DLV_STAT    IS '배송상태(DLV_STAT) R 출고대기 S 배송중 D 배송완료';
COMMENT ON COLUMN TB_DLV.ADD_FEE     IS '도서산간 추가배송비';
COMMENT ON COLUMN TB_DLV.ISLAND_TYPE IS 'JEJU 제주 / ISLAND 그 외 도서산간';
COMMENT ON COLUMN TB_DLV.DLV_CMPL_DT IS '배송완료일';

-- 배송추적 이력 (택배사 조회 결과)
CREATE TABLE TB_DLV_TRACE (
    DLV_NO        VARCHAR2(20)  NOT NULL,
    TRACE_SEQ     NUMBER(5)     NOT NULL,
    TRACE_STAT    CHAR(1)       NOT NULL,
    TRACE_STAT_NM VARCHAR2(50),
    TRACE_LOC     VARCHAR2(100),
    TRACE_DT      DATE,
    REG_DT        DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_DLV_TRACE PRIMARY KEY (DLV_NO, TRACE_SEQ),
    CONSTRAINT FK_TB_DLV_TRACE FOREIGN KEY (DLV_NO) REFERENCES TB_DLV (DLV_NO)
);

COMMENT ON COLUMN TB_DLV_TRACE.TRACE_STAT    IS 'S 배송중 D 배송완료 (중계사 상태코드 변환)';
COMMENT ON COLUMN TB_DLV_TRACE.TRACE_STAT_NM IS '중계사 상태명 (집하, 간선상차, 배송출발, 배달완료 등)';
