-- 주문
CREATE TABLE TB_ORD (
    ORD_NO        VARCHAR2(20)   NOT NULL,
    MBR_ID        VARCHAR2(20)   NOT NULL,
    ORD_STAT      VARCHAR2(2)    NOT NULL,   -- ORD_STAT 공통코드
    ORD_AMT       NUMBER(12)     DEFAULT 0 NOT NULL,   -- 상품금액 합계
    CPN_DC_AMT    NUMBER(12)     DEFAULT 0 NOT NULL,
    PNT_USE_AMT   NUMBER(12)     DEFAULT 0 NOT NULL,
    DLV_FEE       NUMBER(8)      DEFAULT 0 NOT NULL,
    PAY_AMT       NUMBER(12)     DEFAULT 0 NOT NULL,   -- ORD_AMT - CPN_DC_AMT - PNT_USE_AMT + DLV_FEE
    CNCL_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,   -- 부분취소 누적 환불액
    ORD_DT        DATE           DEFAULT SYSDATE NOT NULL,
    PAY_DT        DATE,
    CNFM_DT       DATE,
    CNCL_DT       DATE,
    CNFM_TYPE     CHAR(1),                   -- M 수동, A 자동
    RCV_NM        VARCHAR2(50),
    RCV_HP        VARCHAR2(20),
    RCV_ZIP       VARCHAR2(6),
    RCV_ADDR      VARCHAR2(300),
    RCV_ADDR_DTL  VARCHAR2(200),
    DLV_MSG       VARCHAR2(200),
    ORD_CHNL      VARCHAR2(10)   DEFAULT 'WEB',        -- WEB, MOB, APP
    CNCL_RSN      VARCHAR2(200),
    REG_DT        DATE           DEFAULT SYSDATE NOT NULL,
    UPD_DT        DATE,
    UPD_ID        VARCHAR2(20),
    CONSTRAINT PK_TB_ORD PRIMARY KEY (ORD_NO)
);

CREATE INDEX IX_TB_ORD_01 ON TB_ORD (ORD_DT, ORD_STAT);
CREATE INDEX IX_TB_ORD_02 ON TB_ORD (MBR_ID, ORD_DT);
CREATE INDEX IX_TB_ORD_03 ON TB_ORD (ORD_STAT, UPD_DT);

-- 주문상품
CREATE TABLE TB_ORD_ITEM (
    ORD_NO              VARCHAR2(20)   NOT NULL,
    ITEM_SEQ            NUMBER(4)      NOT NULL,
    PRD_CD              VARCHAR2(20)   NOT NULL,
    SELLER_ID           VARCHAR2(20)   NOT NULL,
    QTY                 NUMBER(5)      NOT NULL,
    UNIT_PRC            NUMBER(10)     NOT NULL,
    ITEM_AMT            NUMBER(12)     NOT NULL,   -- QTY * UNIT_PRC
    ITEM_STAT           CHAR(1)        DEFAULT 'N' NOT NULL,   -- N 정상, C 취소, R 반품요청, X 반품완료
    CPN_DC_SHARE_AMT    NUMBER(12)     DEFAULT 0 NOT NULL,   -- 취소 시 안분된 쿠폰할인
    PNT_SHARE_AMT       NUMBER(12)     DEFAULT 0 NOT NULL,   -- 취소 시 안분된 포인트
    REFUND_AMT          NUMBER(12)     DEFAULT 0 NOT NULL,
    CNCL_DT             DATE,
    REG_DT              DATE           DEFAULT SYSDATE NOT NULL,
    UPD_DT              DATE,
    CONSTRAINT PK_TB_ORD_ITEM PRIMARY KEY (ORD_NO, ITEM_SEQ),
    CONSTRAINT FK_TB_ORD_ITEM FOREIGN KEY (ORD_NO) REFERENCES TB_ORD (ORD_NO)
);

CREATE INDEX IX_TB_ORD_ITEM_01 ON TB_ORD_ITEM (PRD_CD);
CREATE INDEX IX_TB_ORD_ITEM_02 ON TB_ORD_ITEM (SELLER_ID, ORD_NO);

-- 주문상태 변경이력 (changeStat 마다 1건)
CREATE TABLE TB_ORD_STAT_HIST (
    ORD_NO      VARCHAR2(20)   NOT NULL,
    HIST_SEQ    NUMBER(5)      NOT NULL,
    BF_STAT     VARCHAR2(2),
    AF_STAT     VARCHAR2(2)    NOT NULL,
    CHG_RSN     VARCHAR2(200),
    CHG_DT      DATE           DEFAULT SYSDATE NOT NULL,
    CHG_ID      VARCHAR2(20)   NOT NULL,
    CONSTRAINT PK_TB_ORD_STAT_HIST PRIMARY KEY (ORD_NO, HIST_SEQ)
);
