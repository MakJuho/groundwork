-- 정산 (주문상품 단위)
CREATE TABLE TB_STL (
    STL_NO        VARCHAR2(20)  NOT NULL,
    SELLER_ID     VARCHAR2(20)  NOT NULL,
    ORD_NO        VARCHAR2(20)  NOT NULL,
    ITEM_SEQ      NUMBER(5)     NOT NULL,
    PRD_CD        VARCHAR2(20),
    SALE_AMT      NUMBER(12)    DEFAULT 0 NOT NULL,
    COMM_RATE     NUMBER(5,2)   DEFAULT 0 NOT NULL,
    COMM_AMT      NUMBER(12)    DEFAULT 0 NOT NULL,
    STL_AMT       NUMBER(12)    DEFAULT 0 NOT NULL,
    STL_STAT      VARCHAR2(4)   DEFAULT 'RDY' NOT NULL,
    BASE_DT       DATE          NOT NULL,
    CNFM_DT       DATE,
    CNFM_TYPE     CHAR(1),
    CNFM_RSN      VARCHAR2(200),
    PAY_SCHD_DT   CHAR(8),
    PAY_DT        DATE,
    HOLD_RSN      VARCHAR2(200),
    HOLD_DT       DATE,
    HOLD_ID       VARCHAR2(20),
    CNCL_DT       DATE,
    REG_DT        DATE          DEFAULT SYSDATE NOT NULL,
    REG_ID        VARCHAR2(20),
    UPD_DT        DATE,
    UPD_ID        VARCHAR2(20),
    CONSTRAINT PK_TB_STL PRIMARY KEY (STL_NO)
);

CREATE INDEX IX_TB_STL_01 ON TB_STL (ORD_NO, ITEM_SEQ);
CREATE INDEX IX_TB_STL_02 ON TB_STL (STL_STAT, BASE_DT);
CREATE INDEX IX_TB_STL_03 ON TB_STL (SELLER_ID, PAY_SCHD_DT);

COMMENT ON TABLE  TB_STL             IS '정산';
COMMENT ON COLUMN TB_STL.SALE_AMT    IS '판매금액(주문상품금액)';
COMMENT ON COLUMN TB_STL.COMM_RATE   IS '수수료율(%)';
COMMENT ON COLUMN TB_STL.STL_STAT    IS '정산상태(STL_STAT) RDY CNF PAID HOLD CNCL';
COMMENT ON COLUMN TB_STL.BASE_DT     IS '정산기준일(배송완료일)';
COMMENT ON COLUMN TB_STL.CNFM_TYPE   IS 'B 배치확정 M 수동확정';
COMMENT ON COLUMN TB_STL.PAY_SCHD_DT IS '지급예정일 yyyyMMdd';

-- 판매자 지급 (판매자 x 지급예정일 집계)
CREATE TABLE TB_STL_PAY (
    STL_PAY_NO    VARCHAR2(20)  NOT NULL,
    SELLER_ID     VARCHAR2(20)  NOT NULL,
    PAY_SCHD_DT   CHAR(8)       NOT NULL,
    STL_CNT       NUMBER(7)     DEFAULT 0 NOT NULL,
    PAY_AMT       NUMBER(14)    DEFAULT 0 NOT NULL,
    PAY_STAT      CHAR(1)       DEFAULT 'W' NOT NULL,
    PAY_DT        DATE,
    BANK_CD       VARCHAR2(10),
    STL_ACCT_NO   VARCHAR2(30),
    REG_DT        DATE          DEFAULT SYSDATE NOT NULL,
    UPD_DT        DATE,
    CONSTRAINT PK_TB_STL_PAY PRIMARY KEY (STL_PAY_NO)
);

CREATE UNIQUE INDEX UX_TB_STL_PAY_01 ON TB_STL_PAY (SELLER_ID, PAY_SCHD_DT);

COMMENT ON TABLE  TB_STL_PAY          IS '판매자 지급';
COMMENT ON COLUMN TB_STL_PAY.PAY_STAT IS 'W 지급대기 P 지급완료 H 지급보류';

CREATE SEQUENCE SQ_STL_PAY START WITH 1 INCREMENT BY 1 NOCACHE;

-- 정산 배치 실행 이력
CREATE TABLE TB_STL_BATCH_HIST (
    BATCH_SEQ     NUMBER(10)    NOT NULL,
    BATCH_ID      VARCHAR2(30)  NOT NULL,
    BASE_YMD      CHAR(8)       NOT NULL,
    PROC_CNT      NUMBER(10)    DEFAULT 0 NOT NULL,
    RSLT_CD       CHAR(1)       NOT NULL,
    ERR_MSG       VARCHAR2(1000),
    STRT_DT       DATE          NOT NULL,
    END_DT        DATE,
    CONSTRAINT PK_TB_STL_BATCH_HIST PRIMARY KEY (BATCH_SEQ)
);

CREATE SEQUENCE SQ_STL_BATCH_HIST START WITH 1 INCREMENT BY 1 NOCACHE;
