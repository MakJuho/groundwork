-- 결제 (주문당 1건. 재결제 시 기존 건 전체취소 후 신규 채번)
CREATE TABLE TB_PAY (
    PAY_NO        VARCHAR2(20)   NOT NULL,
    ORD_NO        VARCHAR2(20)   NOT NULL,
    PAY_MTHD      VARCHAR2(10)   NOT NULL,   -- CARD, VBANK, PNT
    CARD_CO       VARCHAR2(10),
    INST_MM       NUMBER(2)      DEFAULT 0 NOT NULL,
    FREE_INST_YN  CHAR(1)        DEFAULT 'N' NOT NULL,
    PAY_AMT       NUMBER(12)     DEFAULT 0 NOT NULL,
    CNCL_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,
    PAY_STAT      CHAR(1)        NOT NULL,   -- W 입금대기, A 승인, P 부분취소, C 전체취소, E 취소실패
    PG_TID        VARCHAR2(50),
    APRV_NO       VARCHAR2(20),
    APRV_DT       DATE,
    VBANK_CD      VARCHAR2(10),
    VBANK_NO      VARCHAR2(30),
    VBANK_DUE_DT  CHAR(8),
    DPST_DT       DATE,
    REG_DT        DATE           DEFAULT SYSDATE NOT NULL,
    UPD_DT        DATE,
    CONSTRAINT PK_TB_PAY PRIMARY KEY (PAY_NO)
);

CREATE INDEX IX_TB_PAY_01 ON TB_PAY (ORD_NO);
CREATE INDEX IX_TB_PAY_02 ON TB_PAY (PAY_STAT, REG_DT);
CREATE UNIQUE INDEX UX_TB_PAY_TID ON TB_PAY (PG_TID);

-- 결제 취소 이력 (전체/부분/실패 모두 1건씩)
CREATE TABLE TB_PAY_CNCL (
    PAY_NO        VARCHAR2(20)   NOT NULL,
    CNCL_SEQ      NUMBER(5)      NOT NULL,
    CNCL_TYPE     CHAR(1)        DEFAULT 'A' NOT NULL,   -- A 전체, P 부분
    CNCL_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,
    REMAIN_AMT    NUMBER(12),
    CNCL_RSN      VARCHAR2(200),
    CLM_NO        VARCHAR2(20),
    PG_CNCL_TID   VARCHAR2(50),
    CNCL_STAT     CHAR(1)        NOT NULL,   -- S 성공, F 실패, R 재처리완료
    PG_RES_CD     VARCHAR2(10),
    PG_RES_MSG    VARCHAR2(500),
    RETRY_CNT     NUMBER(3)      DEFAULT 0 NOT NULL,
    CNCL_DT       DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_PAY_CNCL PRIMARY KEY (PAY_NO, CNCL_SEQ),
    CONSTRAINT FK_TB_PAY_CNCL FOREIGN KEY (PAY_NO) REFERENCES TB_PAY (PAY_NO)
);

CREATE INDEX IX_TB_PAY_CNCL_01 ON TB_PAY_CNCL (CNCL_STAT, CNCL_DT);
