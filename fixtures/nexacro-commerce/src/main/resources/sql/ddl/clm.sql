-- 클레임(반품·교환)
CREATE TABLE TB_CLM (
    CLM_NO          VARCHAR2(20)   NOT NULL,
    ORD_NO          VARCHAR2(20)   NOT NULL,
    CLM_TYPE        VARCHAR2(10)   NOT NULL,          -- RTN 반품 / EXC 교환
    CLM_STAT        VARCHAR2(10)   NOT NULL,          -- REQ, COL, CMP, REJ
    CLM_RSN         VARCHAR2(10)   NOT NULL,
    CLM_RSN_DTL     VARCHAR2(1000),
    RTN_FEE         NUMBER(12)     DEFAULT 0 NOT NULL,
    RTN_FEE_PAYER   CHAR(1),                          -- C 고객 / S 판매자
    REFUND_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,
    REFUND_PNT_AMT  NUMBER(12)     DEFAULT 0 NOT NULL,
    REQ_DT          DATE           DEFAULT SYSDATE NOT NULL,
    COL_DT          DATE,
    CMPL_DT         DATE,
    REJ_RSN         VARCHAR2(1000),
    REG_ID          VARCHAR2(20),
    UPD_DT          DATE,
    UPD_ID          VARCHAR2(20),
    CONSTRAINT PK_TB_CLM PRIMARY KEY (CLM_NO)
);

CREATE INDEX IX_TB_CLM_01 ON TB_CLM (ORD_NO, CLM_TYPE, CLM_STAT);
CREATE INDEX IX_TB_CLM_02 ON TB_CLM (REQ_DT);

-- 클레임 상품
CREATE TABLE TB_CLM_ITEM (
    CLM_NO          VARCHAR2(20)   NOT NULL,
    ORD_NO          VARCHAR2(20)   NOT NULL,
    ITEM_SEQ        NUMBER(4)      NOT NULL,
    PRD_CD          VARCHAR2(20),
    QTY             NUMBER(6)      NOT NULL,
    ITEM_AMT        NUMBER(12)     NOT NULL,
    CPN_DC_SHARE_AMT NUMBER(12)    DEFAULT 0 NOT NULL,
    REFUND_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TB_CLM_ITEM PRIMARY KEY (CLM_NO, ITEM_SEQ),
    CONSTRAINT FK_TB_CLM_ITEM_CLM FOREIGN KEY (CLM_NO) REFERENCES TB_CLM (CLM_NO)
);

CREATE INDEX IX_TB_CLM_ITEM_01 ON TB_CLM_ITEM (ORD_NO, ITEM_SEQ);
