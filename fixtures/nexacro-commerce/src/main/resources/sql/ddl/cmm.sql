-- 공통코드 그룹
CREATE TABLE TB_CMM_CODE_GRP (
    GRP_CD      VARCHAR2(20)  NOT NULL,
    GRP_NM      VARCHAR2(100) NOT NULL,
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_DT      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_CMM_CODE_GRP PRIMARY KEY (GRP_CD)
);

-- 공통코드 (CD_VAL1/CD_VAL2: 업무 기준값)
CREATE TABLE TB_CMM_CODE (
    GRP_CD      VARCHAR2(20)  NOT NULL,
    CD          VARCHAR2(20)  NOT NULL,
    CD_NM       VARCHAR2(100) NOT NULL,
    CD_VAL1     VARCHAR2(100),
    CD_VAL2     VARCHAR2(100),
    SORT_ORD    NUMBER(4)     DEFAULT 0 NOT NULL,
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_DT      DATE          DEFAULT SYSDATE NOT NULL,
    UPD_DT      DATE,
    CONSTRAINT PK_TB_CMM_CODE PRIMARY KEY (GRP_CD, CD),
    CONSTRAINT FK_TB_CMM_CODE_GRP FOREIGN KEY (GRP_CD) REFERENCES TB_CMM_CODE_GRP (GRP_CD)
);

-- 채번
CREATE TABLE TB_CMM_SEQ (
    SEQ_ID      VARCHAR2(10)  NOT NULL,
    SEQ_YMD     CHAR(8)       NOT NULL,
    CUR_SEQ     NUMBER(10)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TB_CMM_SEQ PRIMARY KEY (SEQ_ID, SEQ_YMD)
);

-- 휴일 (영업일 계산용)
CREATE TABLE TB_CMM_HOLIDAY (
    HOLI_YMD    CHAR(8)       NOT NULL,
    HOLI_NM     VARCHAR2(50)  NOT NULL,
    CONSTRAINT PK_TB_CMM_HOLIDAY PRIMARY KEY (HOLI_YMD)
);
