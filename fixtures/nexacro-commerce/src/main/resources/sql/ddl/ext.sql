-- 외부연동 송수신 이력 (PG, 택배사)
CREATE TABLE TB_IF_LOG (
    IF_LOG_NO   NUMBER(15)     NOT NULL,
    IF_CD       VARCHAR2(10)   NOT NULL,   -- PG, CARRIER
    IF_SVC      VARCHAR2(30)   NOT NULL,   -- APPROVE, CANCEL, PART_CANCEL, REGISTER, TRACE
    IF_URL      VARCHAR2(300),
    REF_NO      VARCHAR2(30),              -- 주문번호 / PG TID / 송장번호
    REQ_BODY    CLOB,
    RES_BODY    CLOB,
    RES_CD      VARCHAR2(10),
    RES_MSG     VARCHAR2(500),
    SUCC_YN     CHAR(1)        DEFAULT 'N' NOT NULL,
    ELAPSED_MS  NUMBER(10),
    REG_DT      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_IF_LOG PRIMARY KEY (IF_LOG_NO)
);

CREATE SEQUENCE SEQ_TB_IF_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_TB_IF_LOG_01 ON TB_IF_LOG (IF_CD, REG_DT);
CREATE INDEX IX_TB_IF_LOG_02 ON TB_IF_LOG (REF_NO);

