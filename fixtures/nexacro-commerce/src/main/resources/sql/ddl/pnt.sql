-- 포인트 원장
-- PNT_AMT: 적립(+)/차감(-), REMAIN_AMT: 적립건 잔여(사용 가능액), 사용건은 취소 가능 잔액
CREATE TABLE TB_PNT_LEDGER (
    LEDGER_NO       VARCHAR2(20)   NOT NULL,
    MBR_ID          VARCHAR2(20)   NOT NULL,
    PNT_TYPE        VARCHAR2(10)   NOT NULL,          -- EARN, USE, USE_CNCL, EARN_CNCL, EXPIRE, ADJ
    PNT_AMT         NUMBER(12)     NOT NULL,
    REMAIN_AMT      NUMBER(12)     DEFAULT 0 NOT NULL,
    ORD_NO          VARCHAR2(20),
    ORG_LEDGER_NO   VARCHAR2(20),
    EXP_DT          CHAR(8),
    REG_DT          DATE           DEFAULT SYSDATE NOT NULL,
    REG_ID          VARCHAR2(20),
    RMK             VARCHAR2(500),
    CONSTRAINT PK_TB_PNT_LEDGER PRIMARY KEY (LEDGER_NO)
);

CREATE INDEX IX_TB_PNT_LEDGER_01 ON TB_PNT_LEDGER (MBR_ID, EXP_DT);
CREATE INDEX IX_TB_PNT_LEDGER_02 ON TB_PNT_LEDGER (ORD_NO, PNT_TYPE);
CREATE INDEX IX_TB_PNT_LEDGER_03 ON TB_PNT_LEDGER (ORG_LEDGER_NO);

-- 포인트 잔액 (원장 합계와 동기화)
CREATE TABLE TB_PNT_BAL (
    MBR_ID          VARCHAR2(20)   NOT NULL,
    BAL_AMT         NUMBER(12)     DEFAULT 0 NOT NULL,
    UPD_DT          DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_PNT_BAL PRIMARY KEY (MBR_ID)
);
