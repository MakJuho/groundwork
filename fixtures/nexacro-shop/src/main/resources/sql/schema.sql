-- 회원
CREATE TABLE TB_MEMBER (
    MEMBER_ID   VARCHAR2(20)  NOT NULL,
    MEMBER_NM   VARCHAR2(50)  NOT NULL,
    EMAIL       VARCHAR2(100),
    PHONE       VARCHAR2(20),
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_DT      DATE          NOT NULL,
    UPD_DT      DATE,
    CONSTRAINT PK_TB_MEMBER PRIMARY KEY (MEMBER_ID)
);

-- 주문 (ORDER_STAT: 10 주문접수, 20 결제완료, 30 배송중, 40 배송완료, 90 주문취소)
CREATE TABLE TB_ORDER (
    ORDER_NO    VARCHAR2(20)  NOT NULL,
    MEMBER_ID   VARCHAR2(20)  NOT NULL,
    ORDER_STAT  CHAR(2)       DEFAULT '10' NOT NULL,
    TOTAL_AMT   NUMBER(12)    NOT NULL,
    ORDER_DT    DATE          NOT NULL,
    UPD_DT      DATE,
    CONSTRAINT PK_TB_ORDER PRIMARY KEY (ORDER_NO),
    CONSTRAINT FK_TB_ORDER_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TB_MEMBER (MEMBER_ID)
);

-- 상품
CREATE TABLE TB_PRODUCT (
    PRODUCT_CD  VARCHAR2(20)  NOT NULL,
    PRODUCT_NM  VARCHAR2(100) NOT NULL,
    PRICE       NUMBER(12)    NOT NULL,
    STOCK_QTY   NUMBER(8)     DEFAULT 0 NOT NULL,
    REG_DT      DATE          NOT NULL,
    UPD_DT      DATE,
    CONSTRAINT PK_TB_PRODUCT PRIMARY KEY (PRODUCT_CD)
);
