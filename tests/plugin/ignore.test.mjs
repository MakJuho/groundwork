import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createMatcher, DEFAULT_EXCLUDES, globToRegExp, isGeneratedOrMinified, MAX_FILE_BYTES, parseIgnoreFile } from '../../plugin/scripts/lib/ignore.mjs';

test('MAX_FILE_BYTES is 1MB', () => {
  assert.equal(MAX_FILE_BYTES, 1024 * 1024);
});

test('parseIgnoreFile drops comments, blanks and negations', () => {
  assert.deepEqual(parseIgnoreFile('# c\n\nlogs/\n!keep.txt\n  *.bak  \r\n'), ['logs/', '*.bak']);
});

test('globToRegExp handles *, ** and ?', () => {
  assert.ok(globToRegExp('*.log').test('a.log'));
  assert.ok(!globToRegExp('*.log').test('dir/a.log'));
  assert.ok(globToRegExp('src/**/gen').test('src/gen'));
  assert.ok(globToRegExp('src/**/gen').test('src/a/b/gen'));
  assert.ok(globToRegExp('file?.txt').test('file1.txt'));
});

test('default excludes match directories at any depth', () => {
  const m = createMatcher(DEFAULT_EXCLUDES);
  assert.ok(m('node_modules', true));
  assert.ok(m('web/node_modules', true));
  assert.ok(m('a/target/classes/X.class', false));
  assert.ok(!m('src/main/App.java', false));
});

test('dir-only pattern does not match a file with the same name', () => {
  const m = createMatcher(['build/']);
  assert.ok(m('build', true));
  assert.ok(!m('build', false));
});

test('anchored pattern only matches from root', () => {
  const m = createMatcher(['/docs/legacy']);
  assert.ok(m('docs/legacy', true));
  assert.ok(m('docs/legacy/a.md', false));
  assert.ok(!m('src/docs/legacy', true));
});

test('isGeneratedOrMinified detects names, markers and long first lines', () => {
  assert.ok(isGeneratedOrMinified('web/app.min.js', ''));
  assert.ok(isGeneratedOrMinified('package-lock.json', '{'));
  assert.ok(isGeneratedOrMinified('src/Gen.java', '// @generated by protoc\n'));
  assert.ok(isGeneratedOrMinified('src/x.js', 'a'.repeat(1001)));
  assert.ok(!isGeneratedOrMinified('src/order.js', 'export const A = 1;\n'));
});
